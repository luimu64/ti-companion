//! MCP (Model Context Protocol) server exposing the calculator as tools.
//!
//! The server talks to the same single calculator worker the GUI uses, so an
//! agent and the GUI share one connection and never race for the USB device.
//!
//! Run standalone with `ti-companion --mcp` (stdio transport), or alongside the
//! GUI by setting `TI_NSPIRE_MCP=1`.

use crate::{device::DirItem, Done, Job, Session};
use rmcp::{
    handler::server::{router::tool::ToolRouter, wrapper::Parameters},
    model::{ServerCapabilities, ServerConfig},
    schemars, tool, tool_router, ServerHandler, ServiceExt,
};

/// Run the stdio MCP server on the current thread until stdin closes.
pub fn serve_stdio(session: Session) -> Result<(), Box<dyn std::error::Error>> {
    let rt = tokio::runtime::Builder::new_current_thread().enable_all().build()?;
    rt.block_on(async move {
        let service = CalcServer::new(session).serve(rmcp::transport::stdio()).await?;
        service.waiting().await?;
        Ok::<(), Box<dyn std::error::Error>>(())
    })
}

#[derive(Clone)]
pub struct CalcServer {
    session: Session,
    // Read by the router glue generated by #[tool_handler]; the lint cannot see it.
    #[allow(dead_code)]
    tool_router: ToolRouter<Self>,
}

#[derive(Debug, serde::Deserialize, schemars::JsonSchema)]
pub struct PathArg {
    #[schemars(description = "Absolute calculator path, e.g. /docs/foo.tns")]
    pub path: String,
}

#[derive(Debug, serde::Deserialize, schemars::JsonSchema)]
pub struct RenameArg {
    #[schemars(description = "Existing absolute path")]
    pub from: String,
    #[schemars(description = "New absolute path")]
    pub to: String,
}

#[derive(Debug, serde::Deserialize, schemars::JsonSchema)]
pub struct UploadArg {
    #[schemars(description = "Destination absolute path on the calculator")]
    pub path: String,
    #[schemars(description = "Local file to upload")]
    pub local_file: String,
}

#[derive(Debug, serde::Deserialize, schemars::JsonSchema)]
pub struct DownloadArg {
    #[schemars(description = "Absolute path on the calculator")]
    pub path: String,
    #[schemars(description = "Local file to write")]
    pub local_file: String,
}

impl CalcServer {
    pub fn new(session: Session) -> Self {
        Self { session, tool_router: Self::tool_router() }
    }
}

fn err(msg: impl std::fmt::Display) -> Result<String, String> {
    Err(msg.to_string())
}

#[tool_router]
impl CalcServer {
    #[tool(description = "Connect to the TI-Nspire calculator over USB. Safe to call again; returns device info.")]
    fn connect(&self) -> Result<String, String> {
        match self.session.call(Job::Connect) {
            Done::Connected { name, cx2 } => {
                let transport = if cx2 { "CX II" } else { "classic/CX" };
                Ok(format!("connected to {name} ({transport} transport)"))
            }
            Done::Err(e) => err(e),
            _ => err("unexpected reply to connect"),
        }
    }

    #[tool(description = "Get calculator model, OS version, storage and RAM.")]
    fn device_info(&self) -> Result<String, String> {
        match self.session.call(Job::DeviceInfo) {
            Done::DeviceInfo(v) => Ok(v.to_string()),
            Done::Err(e) => err(e),
            _ => err("unexpected reply to device_info"),
        }
    }

    #[tool(description = "List the direct children of a calculator directory.")]
    fn list_directory(&self, Parameters(PathArg { path }): Parameters<PathArg>) -> Result<String, String> {
        match self.session.call(Job::List(path)) {
            Done::Listed { path, items } => Ok(list_json(&path, &items)),
            Done::Err(e) => err(e),
            _ => err("unexpected reply to list_directory"),
        }
    }

    #[tool(description = "Upload a local file to the calculator at the given path.")]
    fn upload_file(&self, Parameters(UploadArg { path, local_file }): Parameters<UploadArg>) -> Result<String, String> {
        let data = std::fs::read(&local_file).map_err(|e| format!("read {local_file}: {e}"))?;
        match self.session.call(Job::Upload(path.clone(), data.clone())) {
            Done::Ok(_) => Ok(format!("uploaded {} bytes to {path}", data.len())),
            Done::Err(e) => err(e),
            _ => err("unexpected reply to upload_file"),
        }
    }

    #[tool(description = "Download a file from the calculator to a local path.")]
    fn download_file(&self, Parameters(DownloadArg { path, local_file }): Parameters<DownloadArg>) -> Result<String, String> {
        match self.session.call(Job::Download(path.clone())) {
            Done::Downloaded { data, .. } => {
                std::fs::write(&local_file, &data).map_err(|e| format!("write {local_file}: {e}"))?;
                Ok(format!("saved {} bytes to {local_file}", data.len()))
            }
            Done::Err(e) => err(e),
            _ => err("unexpected reply to download_file"),
        }
    }

    #[tool(description = "Read a file from the calculator and return its contents as base64.")]
    fn read_file(&self, Parameters(PathArg { path }): Parameters<PathArg>) -> Result<String, String> {
        match self.session.call(Job::Download(path)) {
            Done::Downloaded { data, .. } => Ok(base64(&data)),
            Done::Err(e) => err(e),
            _ => err("unexpected reply to read_file"),
        }
    }

    #[tool(description = "Write base64-encoded data to a file on the calculator.")]
    fn write_file(
        &self,
        Parameters(WriteArg { path, data_base64 }): Parameters<WriteArg>,
    ) -> Result<String, String> {
        let data = unb64(&data_base64).map_err(|e| format!("bad base64: {e}"))?;
        match self.session.call(Job::Upload(path.clone(), data.clone())) {
            Done::Ok(_) => Ok(format!("wrote {} bytes to {path}", data.len())),
            Done::Err(e) => err(e),
            _ => err("unexpected reply to write_file"),
        }
    }

    #[tool(description = "Create a folder on the calculator.")]
    fn create_folder(&self, Parameters(PathArg { path }): Parameters<PathArg>) -> Result<String, String> {
        match self.session.call(Job::Mkdir(path)) {
            Done::Ok(m) => Ok(m),
            Done::Err(e) => err(e),
            _ => err("unexpected reply to create_folder"),
        }
    }

    #[tool(description = "Rename or move a file or folder on the calculator.")]
    fn rename(&self, Parameters(RenameArg { from, to }): Parameters<RenameArg>) -> Result<String, String> {
        match self.session.call(Job::Rename(from, to)) {
            Done::Ok(m) => Ok(m),
            Done::Err(e) => err(e),
            _ => err("unexpected reply to rename"),
        }
    }

    #[tool(description = "Copy a file or folder on the calculator.")]
    fn copy(&self, Parameters(RenameArg { from, to }): Parameters<RenameArg>) -> Result<String, String> {
        match self.session.call(Job::Copy(from, to)) {
            Done::Ok(m) => Ok(m),
            Done::Err(e) => err(e),
            _ => err("unexpected reply to copy"),
        }
    }

    #[tool(description = "Delete a file or folder. Folders must be empty.")]
    fn delete(&self, Parameters(DeleteArg { path, is_dir }): Parameters<DeleteArg>) -> Result<String, String> {
        match self.session.call(Job::DeleteMany(vec![(path, is_dir)])) {
            Done::Ok(m) => Ok(m),
            Done::Err(e) => err(e),
            _ => err("unexpected reply to delete"),
        }
    }

    #[tool(description = "Get size, type and date for a calculator path.")]
    fn file_info(&self, Parameters(PathArg { path }): Parameters<PathArg>) -> Result<String, String> {
        match self.session.call(Job::Info(path)) {
            Done::Info(m) => Ok(m),
            Done::Err(e) => err(e),
            _ => err("unexpected reply to file_info"),
        }
    }
}

#[derive(Debug, serde::Deserialize, schemars::JsonSchema)]
pub struct WriteArg {
    #[schemars(description = "Destination absolute path on the calculator")]
    pub path: String,
    #[schemars(description = "File contents, base64-encoded")]
    pub data_base64: String,
}

#[derive(Debug, serde::Deserialize, schemars::JsonSchema)]
pub struct DeleteArg {
    #[schemars(description = "Absolute path to delete")]
    pub path: String,
    #[schemars(description = "True if the path is a folder")]
    pub is_dir: bool,
}

#[rmcp::tool_handler]
impl ServerHandler for CalcServer {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build()).with_instructions(
            "Drive a physical TI-Nspire calculator over USB: browse, upload, \
             download, rename, copy, delete files and folders. Call `connect` first.",
        )
    }
}

fn list_json(path: &str, items: &[DirItem]) -> String {
    let arr: Vec<serde_json::Value> = items
        .iter()
        .map(|e| {
            serde_json::json!({
                "name": e.name,
                "type": if e.is_dir { "dir" } else { "file" },
                "size": e.size,
                "date": e.date,
            })
        })
        .collect();
    serde_json::json!({ "path": path, "entries": arr }).to_string()
}

const B64: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

fn base64(data: &[u8]) -> String {
    let mut out = String::with_capacity(data.len().div_ceil(3) * 4);
    for chunk in data.chunks(3) {
        let b = [chunk[0], *chunk.get(1).unwrap_or(&0), *chunk.get(2).unwrap_or(&0)];
        let n = ((b[0] as u32) << 16) | ((b[1] as u32) << 8) | b[2] as u32;
        out.push(B64[(n >> 18) as usize & 63] as char);
        out.push(B64[(n >> 12) as usize & 63] as char);
        out.push(if chunk.len() > 1 { B64[(n >> 6) as usize & 63] as char } else { '=' });
        out.push(if chunk.len() > 2 { B64[n as usize & 63] as char } else { '=' });
    }
    out
}

fn unb64(s: &str) -> Result<Vec<u8>, String> {
    let mut vals = Vec::new();
    for c in s.bytes().filter(|b| !b.is_ascii_whitespace()) {
        let v = match c {
            b'A'..=b'Z' => c - b'A',
            b'a'..=b'z' => c - b'a' + 26,
            b'0'..=b'9' => c - b'0' + 52,
            b'+' => 62,
            b'/' => 63,
            b'=' => continue,
            _ => return Err(format!("invalid character {:?}", c as char)),
        };
        vals.push(v as u32);
    }
    let mut out = Vec::with_capacity(vals.len() * 3 / 4);
    for chunk in vals.chunks(4) {
        if chunk.len() < 2 {
            break;
        }
        let n = (chunk[0] << 18)
            | (chunk[1] << 12)
            | (chunk.get(2).copied().unwrap_or(0) << 6)
            | chunk.get(3).copied().unwrap_or(0);
        out.push((n >> 16) as u8);
        if chunk.len() > 2 {
            out.push((n >> 8) as u8);
        }
        if chunk.len() > 3 {
            out.push(n as u8);
        }
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn base64_roundtrip() {
        for case in [&b""[..], b"f", b"fo", b"foo", b"foob", b"fooba", b"foobar"] {
            let encoded = base64(case);
            assert_eq!(unb64(&encoded).unwrap(), case, "case {:?}", case);
        }
        assert_eq!(base64(b"foobar"), "Zm9vYmFy");
        assert_eq!(base64(b"fo"), "Zm8=");
    }
}
